// 封面背景與標題 logo:放進執行期圖片桶(IMG_CACHE),首次安裝後離線也能顯示封面;抓不到不擋安裝
const COVER_PRECACHE = ['./assets/ui/cover_bg_land.webp', './assets/ui/cover_bg_port.webp', './assets/ui/home_logo.webp'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) =>
      cache.addAll(PRECACHE.map((url) => new Request(url, { cache: 'reload' })))
    ).then(() => caches.open(IMG_CACHE)).then((img) =>
      Promise.all(COVER_PRECACHE.map((u) => img.add(new Request(u, { cache: 'reload' })).catch(() => null)))
    )
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE_NAME && k !== IMG_CACHE).map((k) => caches.delete(k))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

// 先精確比對(約 12ms),未命中才用 ignoreSearch(會逐筆掃描整個快取,實測每次約 3 秒)
function cacheMatchFast(cache, req) {
  return cache.match(req).then((hit) => hit || cache.match(req, { ignoreSearch: true }));
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      caches.open(CACHE_NAME).then((cache) =>
        cacheMatchFast(cache, req).then((hit) =>
          hit || fetch(req).catch(() => cache.match('./index.html'))
        )
      )
    );
    return;
  }
  if (RUNTIME_PATHS.some((p) => url.pathname.indexOf(p) >= 0)) {   // 圖片:cache-first,沒有才抓網路並存進執行期桶(只存成功的回應)
    event.respondWith(
      caches.open(IMG_CACHE).then((cache) =>
        cache.match(req).then((hit) => hit || fetch(req).then((res) => {
          if (res && res.ok) cache.put(req, res.clone());
          return res;
        }))
      )
    );
    return;
  }
  event.respondWith(
    caches.open(CACHE_NAME).then((cache) =>
      cacheMatchFast(cache, req).then((hit) => hit || fetch(req))
    )
  );
});
